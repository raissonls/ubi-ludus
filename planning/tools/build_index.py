#!/usr/bin/env python3
"""Rebuild the task index in planning/README.md and planning/traceability.md.

Task files in planning/tasks/ are the source of truth for status. After changing
a task's `status:` line, run:

    python planning/tools/build_index.py

Exits with a non-zero code if a task file is invalid, a dependency does not exist,
or a Must requirement from the PRD has no task (so it can run in CI later).
Standard library only.
"""
import re
import sys
from pathlib import Path

PLANNING = Path(__file__).resolve().parent.parent
ROOT = PLANNING.parent
STATUSES = ("todo", "in-progress", "blocked", "done")
MILESTONES = {
    "M0": ("Discovery spike", "Nov 2-8"),
    "M1": ("Data pipeline", "Nov 9-15"),
    "M2": ("Rights engine", "Nov 16-22"),
    "M3": ("Website core", "Nov 23 - Dec 6"),
    "M4": ("E-mail and operations", "Dec 7-13"),
    "M5": ("Hardening and launch", "Dec 14-20"),
}
PRIORITY_NAME = {"M": "Must", "S": "Should", "C": "Could"}


def parse_task(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError(f"{path}: missing front matter")
    meta = {}
    for line in m.group(1).splitlines():
        key, _, value = line.partition(":")
        value = value.strip()
        if value.startswith("["):
            value = [v.strip() for v in value.strip("[]").split(",") if v.strip()]
        meta[key.strip()] = value
    for key in ("id", "title", "milestone", "priority", "estimate_h", "status", "requirements", "depends_on"):
        if key not in meta:
            raise ValueError(f"{path}: missing '{key}'")
    if meta["status"] not in STATUSES:
        raise ValueError(f"{path}: status must be one of {STATUSES}, got '{meta['status']}'")
    meta["estimate_h"] = int(meta["estimate_h"])
    meta["path"] = path
    return meta


def load_tasks():
    tasks = [parse_task(p) for p in sorted((PLANNING / "tasks").rglob("*.md"))]
    ids = [t["id"] for t in tasks]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        raise ValueError(f"duplicate task ids: {sorted(dupes)}")
    return tasks


def link(task, base=PLANNING):
    rel = task["path"].relative_to(base).as_posix()
    return f"[{task['title']}]({rel})"


def build_index(tasks):
    lines = ["| Milestone | Window | Tasks | Done | Hours | Hours done |", "|---|---|---|---|---|---|"]
    for ms, (name, window) in MILESTONES.items():
        ts = [t for t in tasks if t["milestone"] == ms]
        done = [t for t in ts if t["status"] == "done"]
        lines.append(
            f"| {ms} {name} | {window} | {len(ts)} | {len(done)} | {sum(t['estimate_h'] for t in ts)} | "
            f"{sum(t['estimate_h'] for t in done)} |"
        )
    total = sum(t["estimate_h"] for t in tasks)
    done_h = sum(t["estimate_h"] for t in tasks if t["status"] == "done")
    lines.append(
        f"| **Total** | | **{len(tasks)}** | **{sum(t['status'] == 'done' for t in tasks)}** | **{total}** | **{done_h}** |"
    )
    for ms, (name, window) in MILESTONES.items():
        lines += ["", f"### {ms} {name} ({window})", "",
                  "| ID | Task | Pri | Hours | Status | Depends on |", "|---|---|---|---|---|---|"]
        for t in (t for t in tasks if t["milestone"] == ms):
            lines.append(
                f"| {t['id']} | {link(t)} | {t['priority']} | {t['estimate_h']} | {t['status']} | "
                f"{', '.join(t['depends_on']) or '-'} |"
            )
    return "\n".join(lines)


def prd_requirements():
    reqs = {}
    for line in (ROOT / "docs" / "PRD.md").read_text(encoding="utf-8").splitlines():
        if line.startswith("| FR-"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            reqs[cells[0]] = (PRIORITY_NAME[cells[1]], cells[2])
    return reqs


def build_traceability(tasks, reqs):
    by_req = {}
    for t in tasks:
        for r in t["requirements"]:
            by_req.setdefault(r, []).append(t)
    lines = [
        "# Traceability: requirements to tasks", "",
        "Generated by `python planning/tools/build_index.py`. Do not edit by hand.", "",
        "## Functional requirements", "",
        "| ID | Pri | Requirement | Tasks |", "|---|---|---|---|",
    ]
    problems = []
    for rid, (pri, text) in reqs.items():
        ts = by_req.get(rid, [])
        text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text).replace("**", "")
        short = text if len(text) <= 90 else text[:87].rstrip() + "..."
        if ts:
            cell = ", ".join(f"[{t['id']}]({t['path'].relative_to(PLANNING).as_posix()})" for t in ts)
        elif pri == "Could":
            cell = "[Backlog](../docs/backlog.md)"
        else:
            cell = "**NO TASK**"
            problems.append(f"{pri} requirement {rid} has no task")
        lines.append(f"| {rid} | {pri} | {short} | {cell} |")
    others = sorted(r for r in by_req if not r.startswith("FR-"))
    lines += ["", "## Other references used by tasks", "",
              "Risks (R), open questions (Q), success criteria (S) and non-functional areas (NFR) from the PRD.", "",
              "| Reference | Tasks |", "|---|---|"]
    for r in others:
        lines.append(f"| {r} | " + ", ".join(t["id"] for t in by_req[r]) + " |")
    return "\n".join(lines) + "\n", problems


def main():
    tasks = load_tasks()
    ids = {t["id"] for t in tasks}
    problems = []
    for t in tasks:
        for d in t["depends_on"]:
            if d not in ids:
                problems.append(f"{t['id']} depends on unknown task {d}")
        if t["milestone"] not in MILESTONES:
            problems.append(f"{t['id']} has unknown milestone {t['milestone']}")

    reqs = prd_requirements()
    trace, trace_problems = build_traceability(tasks, reqs)
    problems += trace_problems
    with open(PLANNING / "traceability.md", "w", encoding="utf-8", newline="\n") as f:
        f.write(trace)

    readme = PLANNING / "README.md"
    text = readme.read_text(encoding="utf-8")
    start, end = "<!-- INDEX:START -->", "<!-- INDEX:END -->"
    if start not in text or end not in text:
        problems.append("planning/README.md is missing the INDEX markers")
    else:
        head, rest = text.split(start, 1)
        _, tail = rest.split(end, 1)
        new = head + start + "\n\n" + build_index(tasks) + "\n\n" + end + tail
        with open(readme, "w", encoding="utf-8", newline="\n") as f:
            f.write(new)

    print(f"{len(tasks)} tasks, {sum(t['estimate_h'] for t in tasks)} h, "
          f"{sum(t['status'] == 'done' for t in tasks)} done")
    for p in problems:
        print("PROBLEM:", p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
